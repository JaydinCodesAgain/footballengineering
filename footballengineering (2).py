# New feature extractor
def enhanced_jersey_features(crop):
    if crop is None or crop.size == 0:
        raise ValueError("Empty jersey crop")

    h, w = crop.shape[:2]

    # Focus further on the centre of the jersey.
    focused = crop[
        int(h * 0.07):max(int(h * 0.93), 1),
        int(w * 0.10):max(int(w * 0.90), 1)
    ]

    if focused.size == 0:
        focused = crop

    focused = cv2.resize(focused, (48, 64))

    hsv = cv2.cvtColor(focused, cv2.COLOR_BGR2HSV)
    lab = cv2.cvtColor(focused, cv2.COLOR_BGR2LAB)

    # Exclude common pitch-green pixels.
    grass = cv2.inRange(
        hsv,
        np.array([35, 40, 30], dtype=np.uint8),
        np.array([95, 255, 255], dtype=np.uint8)
    )

    mask = cv2.bitwise_not(grass)

    # Avoid an empty or nearly empty feature.
    if cv2.countNonZero(mask) < focused.shape[0] * focused.shape[1] * 0.25:
        mask = None

    def normalized(hist):
        hist = hist.flatten().astype(np.float32)
        return hist / (hist.sum() + 1e-8)

    # Hue and saturation: jersey colour.
    hs_hist = normalized(
        cv2.calcHist(
            [hsv], [0, 1], mask,
            [18, 8], [0, 180, 0, 256]
        )
    )

    # LAB chromatic channels: alternative colour representation.
    ab_hist = normalized(
        cv2.calcHist(
            [lab], [1, 2], mask,
            [12, 12], [0, 256, 0, 256]
        )
    )

    # Brightness matters for white, black and dark kits.
    brightness_hist = normalized(
        cv2.calcHist(
            [hsv], [2], mask,
            [12], [0, 256]
        )
    )

    features = np.concatenate([
        hs_hist * 0.50,
        ab_hist * 0.35,
        brightness_hist * 0.15
    ])

    return features.astype(np.float32)


