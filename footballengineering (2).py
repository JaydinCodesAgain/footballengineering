def extract_jersey(frame, xyxy):
    frame_h, frame_w = frame.shape[:2]

    x1, y1, x2, y2 = map(int, xyxy)

    player_w = x2 - x1
    player_h = y2 - y1

    if player_w <= 0 or player_h < MIN_PLAYER_HEIGHT:
        return None

    left = max(0, int(x1 + 0.20 * player_w))
    right = min(frame_w, int(x1 + 0.80 * player_w))

    top = max(0, int(y1 + 0.20 * player_h))
    bottom = min(frame_h, int(y1 + 0.55 * player_h))

    if right <= left or bottom <= top:
        return None

    crop = frame[top:bottom, left:right]

    return crop if crop.size else None


